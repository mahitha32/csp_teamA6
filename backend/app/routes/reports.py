"""
app/routes/reports.py
Digital Work Completion Report Generation
"""
from flask import Blueprint, send_file
from flask_jwt_extended import jwt_required
from app import get_db
import io

reports_bp = Blueprint("reports", __name__)

@reports_bp.route("/completion_pdf/<complaint_id>", methods=["GET"])
@jwt_required()
def generate_completion_pdf(complaint_id):
    db = get_db()
    with db.cursor() as cursor:
        cursor.execute("SELECT * FROM complaints WHERE complaint_id = %s", (complaint_id,))
        complaint = cursor.fetchone()
        
    if not complaint:
        return {"success": False, "message": "Complaint not found"}, 404

    # Dummy PDF Generation Logic using raw bytes (In production, use ReportLab)
    pdf_content = f"Smart Village Governance Platform\n\nWork Completion Report\n\nComplaint ID: {complaint_id}\nCategory: {complaint['category']}\nStatus: {complaint['status']}\nResolution Notes: {complaint.get('resolution_notes', 'N/A')}\n\nGenerated by Digital Panchayat System"
    
    return send_file(
        io.BytesIO(pdf_content.encode('utf-8')),
        mimetype="text/plain", # Mime type placeholder, should be application/pdf
        as_attachment=True,
        download_name=f"Work_Completion_{complaint_id}.txt"
    )
